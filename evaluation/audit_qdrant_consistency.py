"""Audit consistency between ``store.db`` and the Qdrant collection.

For every document marked as ``is_latest=1 AND status='active'`` in the
SQLite store, verify that Qdrant contains at least one chunk with
``canonical_id == doc.canonical_id`` AND ``is_latest == True``.

The mismatch list reveals indexing gaps that bias retrieval evaluation
(latest documents not searchable, only revoked versions returned).

Outputs a report to ``evaluation/results/qdrant_index_consistency.md``.
"""

from __future__ import annotations

import sqlite3
import sys
from collections import Counter
from pathlib import Path
from typing import List, Optional, Tuple

import requests

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from config import config  # noqa: E402

REPORT_PATH = ROOT / "evaluation" / "results" / "qdrant_index_consistency.md"
STORE_DB = ROOT / "data" / "store.db"


def qdrant_count(canonical_id: str, is_latest_filter: Optional[bool]) -> int:
    must = [{"key": "canonical_id", "match": {"value": canonical_id}}]
    if is_latest_filter is not None:
        must.append({"key": "is_latest", "match": {"value": is_latest_filter}})
    url = (
        f"http://{config.QDRANT_HOST}:{config.QDRANT_PORT}"
        f"/collections/{config.QDRANT_COLLECTION_NAME}/points/count"
    )
    r = requests.post(
        url, json={"exact": True, "filter": {"must": must}}, timeout=10,
    )
    return r.json().get("result", {}).get("count", 0)


def main() -> int:
    conn = sqlite3.connect(STORE_DB)
    cur = conn.execute(
        """
        SELECT canonical_id, doc_type, authority, version_year
        FROM documents
        WHERE is_latest=1 AND status='active' AND canonical_id IS NOT NULL
        """
    )
    docs: List[Tuple[str, str, str, str]] = cur.fetchall()
    print(f"Active+latest docs in store.db: {len(docs)}")

    missing: List[Tuple[str, str, str, str, int]] = []
    for i, (cid, dtype, auth, ver) in enumerate(docs, 1):
        cnt_latest = qdrant_count(cid, True)
        if cnt_latest == 0:
            cnt_any = qdrant_count(cid, None)
            missing.append((cid, dtype or "", auth or "", ver or "", cnt_any))
        if i % 500 == 0:
            print(f"  checked {i}/{len(docs)}; missing so far: {len(missing)}")

    by_type: Counter = Counter(m[1] for m in missing)
    by_auth: Counter = Counter(m[2] for m in missing)
    has_old_only = sum(1 for m in missing if m[4] > 0)
    fully_missing = sum(1 for m in missing if m[4] == 0)

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    out = []
    out.append("# Qdrant Index Consistency Audit\n")
    out.append("_Auto-generated by `evaluation/audit_qdrant_consistency.py`._\n")
    out.append("## Resumo\n")
    out.append(
        f"- Documentos ativos + latest no `store.db`: **{len(docs)}**"
    )
    out.append(
        f"- Sem chunks `is_latest=true` em Qdrant: **{len(missing)}**"
        f" ({len(missing)/len(docs)*100:.1f}%)"
    )
    out.append(
        f"- Destes, **{has_old_only}** têm chunks de versões antigas indexados"
        f" (só a versão atual está faltando)"
    )
    out.append(
        f"- Destes, **{fully_missing}** não têm NENHUM chunk em Qdrant"
        " (documento totalmente fora do índice)\n"
    )

    out.append("## Distribuição dos faltantes por `doc_type`")
    out.append("| doc_type | count |")
    out.append("|---|---|")
    for k, v in by_type.most_common():
        out.append(f"| {k or '(empty)'} | {v} |")
    out.append("")

    out.append("## Distribuição dos faltantes por `authority`")
    out.append("| authority | count |")
    out.append("|---|---|")
    for k, v in by_auth.most_common():
        out.append(f"| {k or '(empty)'} | {v} |")
    out.append("")

    out.append("## Sample (primeiros 30 com versões antigas indexadas)\n")
    out.append("Estes são os mais críticos: o usuário recebe documentos REVOGADOS"
               " porque a versão vigente não está no índice.\n")
    out.append("| canonical_id | doc_type | authority | version (store.db) | chunks_old |")
    out.append("|---|---|---|---|---|")
    for cid, dtype, auth, ver, cnt in [m for m in missing if m[4] > 0][:30]:
        out.append(f"| {cid} | {dtype} | {auth} | {ver} | {cnt} |")
    out.append("")

    out.append("## Impacto no estudo de qualidade do RAG\n")
    out.append(
        "1. **Métricas de recuperação subestimam qualidade real do retriever**:"
        " quando o golden set aponta para a versão atual mas só a antiga está indexada,"
        " o retriever falha por falta de dado, não por baixa qualidade.\n"
        "2. **Risco para o usuário**: respostas baseadas em normas revogadas."
        " O `Generator` atualmente não reduz peso de chunks com `is_latest=false`"
        " quando a versão vigente está ausente.\n"
        "3. **Próxima ação**: investigar a pipeline de ingestão / re-indexar"
        " os 266 documentos faltantes ANTES das próximas avaliações end-to-end,"
        " caso contrário thresholds calibrados ficarão enviesados."
    )

    REPORT_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"\nReport written to: {REPORT_PATH}")
    print(f"Missing: {len(missing)}/{len(docs)} ({len(missing)/len(docs)*100:.1f}%)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
